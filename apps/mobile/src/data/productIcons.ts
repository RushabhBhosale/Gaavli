const escape = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const COMPILED = RULES.map((rule) => ({
  ...rule,
  groupSet: rule.groups ? new Set(rule.groups) : null,
  // Whole words only, so "pea" never matches "peach" and "ale" never
  // matches "pale"; a trailing s/es covers simple plurals.
  pattern: new RegExp(
    `(?:^|[^a-z])(?:${[...rule.words]
      .sort((a, b) => b.length - a.length)
      .map((word) => escape(word.toLowerCase()).replace(/ /g, "[\\s-]+"))
      .join("|")})(?:e?s)?(?=$|[^a-z])`,
  ),
}));

export type ProductIconMatch = {
  icon: string;
  badge: ProductIconBadge | null;
  // False when only the group's general icon applied.
  specific: boolean;
};
const cache = new Map<string, ProductIconMatch>();

export function productIconFor(product: {
  nameEn: string;
  productGroup?: string | null;
}): ProductIconMatch {
  const group = product.productGroup ?? "";
  const key = `${group}\u0000${product.nameEn}`;
  const saved = cache.get(key);
  if (saved) return saved;
  const name = product.nameEn.normalize("NFKC").toLowerCase();
  const rule = COMPILED.find(
    (candidate) =>
      (!candidate.groupSet || candidate.groupSet.has(group)) &&
      candidate.pattern.test(name),
  );
  const badge: ProductIconBadge | null =
    rule?.crop && group === "farm_inputs"
      ? "seed"
      : rule?.crop && group === "plants_garden"
        ? "plant"
        : null;
  const match: ProductIconMatch = rule
    ? { icon: rule.icon, badge, specific: true }
    : {
        icon: GROUP_ICON[group] ?? DEFAULT_PRODUCT_ICON,
        badge: null,
        specific: false,
      };
  if (cache.size > 5000) cache.clear();
  cache.set(key, match);
  return match;
}

